package trace.build

import java.io.File
import java.net.URI
import java.net.http.HttpClient
import java.net.http.HttpRequest
import java.net.http.HttpResponse
import java.security.MessageDigest
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit
import org.gradle.api.GradleException
import org.gradle.api.logging.Logger

/** Which server build to run. */
internal data class ServerSpec(
    val project: String,
    val version: String,
    val build: Int,
    val sha256: String,
) {
    val jarName: String = "$project-$version-$build.jar"
}

/** The marker the harness prints; the launcher watches for it. */
internal const val HARNESS_MARKER = "[TRACE-HARNESS]"

/** Result of one server run. */
internal class ServerRun(
    val exitCode: Int,
    val timedOut: Boolean,
    val killed: Boolean,
    val tail: List<String>,
) {
    fun describe(): String = "exit=$exitCode timedOut=$timedOut killed=$killed\n" + tail.joinToString("\n")
}

/**
 * Downloading, preparing and running a pinned Paper or Folia server.
 *
 * Shared by the scenario task and the crash-injection task so that "how a test server is set up"
 * exists exactly once: a benchmark and a crash test have to run on identical servers or neither
 * number means anything.
 */
internal object ServerRuntime {

    fun resolveJar(spec: ServerSpec, cacheDir: File, contact: String, logger: Logger): File {
        cacheDir.mkdirs()
        val expected = spec.sha256.lowercase()
        val target = cacheDir.resolve(spec.jarName)
        if (target.isFile && sha256Of(target) == expected) {
            return target
        }
        // PaperMC's content store addresses objects by their hash, so the pinned checksum is also
        // the download address: there is no window in which we fetch something unverified.
        val url = "https://fill-data.papermc.io/v1/objects/$expected/${spec.jarName}"
        logger.lifecycle("Downloading ${spec.jarName} from PaperMC")
        val client = HttpClient.newBuilder().followRedirects(HttpClient.Redirect.NORMAL).build()
        val request = HttpRequest.newBuilder(URI.create(url))
            .header("User-Agent", "Trace-build/0.1 (+https://gravaxis.in; $contact)")
            .GET()
            .build()
        val tmp = File(cacheDir, "${spec.jarName}.tmp")
        val response = client.send(request, HttpResponse.BodyHandlers.ofFile(tmp.toPath()))
        if (response.statusCode() != 200) {
            tmp.delete()
            throw GradleException("Download of $url failed with HTTP ${response.statusCode()}")
        }
        val actual = sha256Of(tmp)
        if (actual != expected) {
            tmp.delete()
            throw GradleException("Checksum mismatch for ${spec.jarName}: expected $expected, got $actual")
        }
        tmp.renameTo(target)
        return target
    }

    /**
     * Writes a deterministic, offline, minimal-work server directory.
     *
     * @param keepWorld true when a later phase of the same test has to see what the first phase
     *     wrote — a crash test restarts into the same directory on purpose.
     */
    fun prepareRunDirectory(dir: File, port: Int, pluginJars: Iterable<File>, keepWorld: Boolean) {
        dir.mkdirs()
        if (!keepWorld) {
            listOf("world", "world_nether", "world_the_end").forEach { dir.resolve(it).deleteRecursively() }
        }
        dir.resolve("harness-result.json").delete()
        dir.resolve("eula.txt").writeText(
            """
            # The Minecraft EULA (https://aka.ms/MinecraftEULA) was accepted by the repository owner
            # for these throwaway test servers. See docs/decisions/0001-platform-target.md.
            eula=true

            """.trimIndent()
        )
        dir.resolve("server.properties").writeText(
            """
            # Generated by Trace's test harness. Deterministic, offline, minimal work per tick.
            # Bound to loopback on a task-specific port so parallel scenarios never collide.
            online-mode=false
            server-ip=127.0.0.1
            server-port=$port
            enable-status=false
            enable-query=false
            enable-rcon=false
            level-type=minecraft\:flat
            level-seed=trace-harness
            generate-structures=false
            spawn-protection=0
            spawn-monsters=false
            spawn-npcs=false
            spawn-animals=false
            allow-nether=false
            view-distance=4
            simulation-distance=4
            max-players=5
            enable-command-block=false
            sync-chunk-writes=false
            motd=Trace test server

            """.trimIndent()
        )
        val pluginsDir = dir.resolve("plugins")
        pluginsDir.mkdirs()
        pluginsDir.listFiles { f -> f.isFile && f.name.endsWith(".jar") }?.forEach { it.delete() }
        pluginJars.forEach { jar -> jar.copyTo(pluginsDir.resolve(jar.name), overwrite = true) }
    }

    fun command(
        javaExecutable: String,
        jvmArgs: List<String>,
        serverJar: File,
        scenario: String,
        params: Map<String, String>,
    ): List<String> = buildList {
        add(javaExecutable)
        addAll(jvmArgs)
        add("-Dcom.mojang.eula.agree=true")
        add("-Dtrace.harness.scenario=$scenario")
        if (params.isNotEmpty()) {
            add("-Dtrace.harness.params=" + params.entries.joinToString(",") { "${it.key}=${it.value}" })
        }
        add("-jar")
        add(serverJar.absolutePath)
        add("--nogui")
    }

    /**
     * Runs the server to completion, or kills it part-way through.
     *
     * @param killAfterMarker when non-null, the first output line containing it arms a hard kill
     *     (`destroyForcibly`, i.e. SIGKILL or TerminateProcess) [killDelayMillis] later. That is how
     *     the crash rig simulates a machine dying mid-write: no shutdown hooks, no flush, no mercy.
     */
    fun run(
        command: List<String>,
        directory: File,
        logFile: File,
        logger: Logger,
        timeoutSeconds: Long,
        killAfterMarker: String? = null,
        killDelayMillis: Long = 0,
    ): ServerRun {
        logger.lifecycle("Starting ${directory.name}: ${command.last { it.endsWith(".jar") }.substringAfterLast(File.separatorChar)}")
        val process = ProcessBuilder(command).directory(directory).redirectErrorStream(true).start()
        process.outputStream.close()

        val tail = ArrayDeque<String>()
        val killedByUs = java.util.concurrent.atomic.AtomicBoolean(false)
        val killArmed = java.util.concurrent.atomic.AtomicBoolean(false)
        val pumpDone = CountDownLatch(1)
        val pump = Thread {
            try {
                process.inputStream.bufferedReader().use { reader ->
                    logFile.bufferedWriter().use { out ->
                        reader.lineSequence().forEach { line ->
                            out.write(line)
                            out.newLine()
                            out.flush()
                            if (line.contains(HARNESS_MARKER)) {
                                logger.lifecycle(line.substringAfter(HARNESS_MARKER).trim())
                            } else {
                                logger.info(line)
                            }
                            synchronized(tail) {
                                tail.addLast(line)
                                if (tail.size > 80) tail.removeFirst()
                            }
                            if (killAfterMarker != null &&
                                line.contains(killAfterMarker) &&
                                killArmed.compareAndSet(false, true)
                            ) {
                                val killer = Thread {
                                    Thread.sleep(killDelayMillis)
                                    logger.lifecycle("Killing the server ${killDelayMillis}ms after '$killAfterMarker'")
                                    killedByUs.set(true)
                                    process.destroyForcibly()
                                }
                                killer.isDaemon = true
                                killer.start()
                            }
                        }
                    }
                }
            } catch (_: java.io.IOException) {
                // The stream dies with the process when we kill it; that is the expected path.
            } finally {
                pumpDone.countDown()
            }
        }
        pump.isDaemon = true
        pump.start()

        val finished = process.waitFor(timeoutSeconds, TimeUnit.SECONDS)
        if (!finished) {
            process.destroyForcibly()
            process.waitFor(30, TimeUnit.SECONDS)
        }
        pumpDone.await(10, TimeUnit.SECONDS)
        val snapshot = synchronized(tail) { tail.toList() }
        return ServerRun(
            exitCode = if (process.isAlive) -1 else process.exitValue(),
            timedOut = !finished,
            killed = killedByUs.get(),
            tail = snapshot,
        )
    }

    fun sha256Of(file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input ->
            val buffer = ByteArray(1 shl 16)
            while (true) {
                val read = input.read(buffer)
                if (read < 0) break
                digest.update(buffer, 0, read)
            }
        }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

    /** Minimal reader for the harness result file: status plus the failure list. */
    fun readResult(file: File): Pair<Boolean, String> {
        if (!file.isFile) return false to "no result file at $file"
        val text = file.readText()
        val passed = Regex("\"status\"\\s*:\\s*\"PASS\"").containsMatchIn(text)
        return passed to text
    }
}
